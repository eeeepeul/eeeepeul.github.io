-- Drawings saved from the drawing pad of the second page, kept for everyone to put on their match.
create table if not exists public.shared_drawings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  image text not null,
  aspect real not null,
  constraint shared_drawings_image_check check (
    image like 'data:image/png;base64,%' and length(image) <= 300000
  ),
  constraint shared_drawings_aspect_check check (aspect between 0.02 and 50)
);

create index if not exists shared_drawings_id_idx on public.shared_drawings (id desc);

alter table public.shared_drawings enable row level security;

grant select, insert on public.shared_drawings to anon, authenticated;
grant usage, select on sequence public.shared_drawings_id_seq to anon, authenticated;
revoke insert (id, created_at) on public.shared_drawings from anon, authenticated;

drop policy if exists "read shared drawings" on public.shared_drawings;
create policy "read shared drawings"
  on public.shared_drawings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "save valid shared drawings" on public.shared_drawings;
create policy "save valid shared drawings"
  on public.shared_drawings
  for insert
  to anon, authenticated
  with check (
    image like 'data:image/png;base64,%'
    and length(image) <= 300000
    and aspect between 0.02 and 50
  );

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'shared_drawings'
  ) then
    alter publication supabase_realtime add table public.shared_drawings;
  end if;
end
$$;
